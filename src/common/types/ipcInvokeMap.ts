export type IpcInvokeChannel = keyof IpcInvokeMap;
/** チャンネルの引数（レンダラーが渡す順） */
export type IpcInvokeArgs<C extends IpcInvokeChannel> = Parameters<IpcInvokeMap[C]>;
/** チャンネルの戻り値（ハンドラーが返す値。Promise は外す） */
export type IpcInvokeResult<C extends IpcInvokeChannel> = Awaited<ReturnType<IpcInvokeMap[C]>>;
